UNDER_TEST = 0
ACTIVATION = 210
FALCON = 215
DELAY = 5
# ycashd 6.22.0-beta2's fees for the merges of the merge check, Yellowback not live (the plain
# post-quantum rate at its default): PQBuilderFee on the estimated size (FN-DSA 2 inputs; SLH-DSA 3 + 1 ECC
# input to Sapling). yewd must charge the same.
MERGE_FEES = {'fn2': Decimal('0.000535'), 'slh3_ecc': Decimal('0.000815')}
CHECKS = ('lock_lifetime', 'funding_change', 'merge', 'help_text')
YEWD = bool(os.environ.get('YEWD_BIN'))

_start_node = util.start_node


def _start_node_one_pair(i, *a, **kw):
    """Only node 0 becomes a pair under YEWD_BIN; node 1 stays a plain ycashd."""
    saved = os.environ.get('YEWD_BIN')
    if i == UNDER_TEST or saved is None:
        return _start_node(i, *a, **kw)
    os.environ.pop('YEWD_BIN')
    try:
        return _start_node(i, *a, **kw)
    finally:
        os.environ['YEWD_BIN'] = saved


util.start_node = _start_node_one_pair


def outpoints(entries):
    return {(e['txid'], e['vout']) for e in entries}


def wait_until(pred, what, timeout=60):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            if pred():
                return
        except (JSONRPCException, OSError):
            pass
        time.sleep(0.25)
    raise AssertionError('timed out waiting for ' + what)


class GapParity(BitcoinTestFramework):

    def __init__(self):
        super().__init__()
        self.num_nodes = 2
        self.setup_clean_chain = True

    def add_options(self, parser):
        parser.add_option('--checks', dest='checks', default=','.join(CHECKS),
                          help='comma-separated checks to run (%s)' % ', '.join(CHECKS))

    def node_args(self, i):
        return [nuparams(VAULT_BRANCH_ID, ACTIVATION), '-pqfalconheight=%d' % FALCON, '-debug=vault']

    def setup_network(self, split=False):
        self.nodes = [util.start_node(i, self.options.tmpdir, self.node_args(i)) for i in range(self.num_nodes)]
        connect_nodes_bi(self.nodes, 0, 1)
        self.is_network_split = False
        self.sync_all()

    def mine(self, n=1):
        self.sync_all()
        hashes = self.nodes[1].generate(n)
        self.sync_all()
        return hashes

    def sync_all(self, do_mempool_sync=True):
        sync_blocks(self.nodes)
        if do_mempool_sync:
            sync_mempools(self.nodes)

    def params(self, amount, source=None):
        p = {'tag': 'TEST', 'setid': self.setid, 'delay': DELAY,
             'ownerheight': self.nodes[0].getblockcount() + 1000, 'amount': amount}
        if source is not None:
            p['from'] = source
        return p

    def inputs_of(self, node, txid):
        return {(i['txid'], i['vout']) for i in node.getrawtransaction(txid, 1)['vin']}

    def run_test(self):
        n0, n1 = self.nodes
        print('column: %s' % ('yewd' if YEWD else 'ycashd'))
        print('activation; node 0 funded from node 1; a released set')
        self.mine(ACTIVATION - n1.getblockcount())
        for _ in range(4):
            n1.sendtoaddress(n0.getnewaddress(), 20)
        self.mine(1)
        self.setid = n1.set_create({'seats': 3, 'unlockthreshold': 2, 'cancelthreshold': 1, 'slashthreshold': 2,
                                    'maturity': 2, 'livenesswindow': 50, 'bondmin': 1, 'ratewindow': 20})['setid']
        self.mine(1)
        assert_equal(n0.set_getinfo(self.setid)['released'], True)
        for name in self.options.checks.split(','):
            if name not in CHECKS:
                raise AssertionError('unknown check %r' % name)
            getattr(self, name)()
        print('all checks passed (%s)' % ('yewd' if YEWD else 'ycashd'))

    # ------------------------------------------------------------------ the checks

    def lock_lifetime(self):
        """Audit L-1 (ycash6 vault.cpp FundScope; qa wallet_beta2_followups2.py lock_lifetime)."""
        print('lock_lifetime: an accepted vault_lock holds no coin lock')
        n0 = self.nodes[0]
        ecc = n0.getnewaddress()
        pq = n0.getnewaddress('', 'pqslh')
        kept = n0.getnewaddress()
        n0.sendtoaddress(ecc, 10)
        n0.sendtoaddress(pq, 10)
        n0.sendtoaddress(kept, 3)
        self.mine(1)
        kept_op = [(u['txid'], u['vout']) for u in n0.listunspent(1, 9999999, [kept])]
        assert_equal(len(kept_op), 1)
        n0.lockunspent(False, [{'txid': kept_op[0][0], 'vout': kept_op[0][1]}])
        locked_before = outpoints(n0.listlockunspent())
        assert kept_op[0] in locked_before
        txids = {}
        for name, source in (('ecc', ecc), ('pq', pq), ('default', None)):
            txids[name] = n0.vault_lock(self.params(Decimal('1'), source))['txid']
            assert txids[name] in n0.getrawmempool(), name
            ins = self.inputs_of(n0, txids[name])
            assert ins, name
            assert_equal(outpoints(n0.listlockunspent()), locked_before)
            assert not (ins & outpoints(n0.listunspent(0))), name
            assert_equal(n0.gettransaction(txids[name])['confirmations'], 0)
        self.mine(1)
        for name in txids:
            assert_equal(n0.gettransaction(txids[name])['confirmations'], 1)
        assert_equal(outpoints(n0.listlockunspent()), locked_before)
        n0.lockunspent(True, [{'txid': kept_op[0][0], 'vout': kept_op[0][1]}])
        assert_equal(n0.listlockunspent(), [])

    def funding_change(self):
        """ycash6 vault.cpp Fund (NewWalletKey change), wallet.cpp IsChange; qa vault_pq_wallet.py."""
        print('funding_change: the default funding change is listed sent and received')
        n0 = self.nodes[0]
        lk = n0.vault_lock(self.params(Decimal('2')))
        self.mine(1)
        listed = set(n0.getaddressesbyaccount(''))
        book = {a for e in n0.listaddresses() for a in e.get('transparent', {}).get('addresses', [])}
        gt = n0.gettransaction(lk['txid'])
        changes = 0
        for out in n0.decoderawtransaction(gt['hex'])['vout']:
            for a in out['scriptPubKey'].get('addresses', []):
                changes += 1
                assert a not in listed and a not in book, a
                assert_equal(sorted(d['category'] for d in gt['details'] if d.get('address') == a),
                             ['receive', 'send'])
        assert_equal(changes, 1)


    def help_text(self):
        """ycashd's help, from the table yewd answers it from; getunconfirmedbalance; the NU5 refusals."""
        print('help_text: the wallet methods answer ycashd\'s help')
        n0, n1 = self.nodes
        here = os.path.dirname(os.path.abspath(__file__))
        with open(os.path.join(here, '..', 'facade', 'src', 'ycashd_rpc.json')) as f:
            table = json.load(f)['methods']
        # The table is read from a ycashd with Yellowback live, -experimentalfeatures and
        # -developerencryptwallet, and walletlock / walletpassphrase from an encrypted wallet: the
        # methods whose help depends on that (here: Yellowback is not live) are compared where this
        # run's ycashd (node 1) reproduces the table's text, and must be most of them.
        same, skipped, differ = 0, [], []
        for m in sorted(table):
            ref = n1.help(m)
            if ref != table[m]['help']:
                skipped.append(m)
                continue
            same += 1
            if n0.help(m) != ref:
                differ.append(m)
        print('  %d methods compared; not reproduced by this ycashd: %s' % (same, ' '.join(skipped)))
        assert_equal(differ, [])
        assert same >= 60, same
        n1.sendtoaddress(n0.getnewaddress(), Decimal('0.5'))
        sync_mempools(self.nodes)
        assert_equal(n0.getunconfirmedbalance(), n0.getwalletinfo()['unconfirmed_balance'])
        assert_equal(n0.getunconfirmedbalance(), Decimal('0.5'))
        self.mine(1)
        assert_equal(n0.getunconfirmedbalance(), Decimal('0'))
        for m, args in (('z_getnewaccount', []), ('z_listaccounts', []), ('z_getaddressforaccount', [0]),
                        ('z_getbalanceforaccount', [0])):
            for node in (n0, n1):
                try:
                    getattr(node, m)(*args)
                    raise AssertionError('%s answered' % m)
                except JSONRPCException as e:
                    assert_equal((e.error['code'], e.error['message']),
                                 (-8, 'Unified-address accounts require the NU5 network upgrade, which is not active on Ycash.'))
        errs = []
        for node in (n0, n1):
            try:
                node.z_getnewaccount(1)
                raise AssertionError('z_getnewaccount 1 answered')
            except JSONRPCException as e:
                errs.append((e.error['code'], e.error['message']))
        assert_equal(errs[0], errs[1])


    def merge(self):
        """z_mergetoaddress (ycash6 rpcwallet.cpp:6424; qa wallet_address_matrix.py, the merge rows)."""
        print('merge: z_mergetoaddress from post-quantum, ECC and Sapling sources')
        n0, n1 = self.nodes

        def merge(froms, to, fee=None, limit=None):
            return n0.z_mergetoaddress(froms, to, fee, limit, None, None, 'NoPrivacy')

        def refused(substr, *args):
            try:
                merge(*args)
            except JSONRPCException as e:
                assert substr in e.error['message'], (substr, e.error)
                return e.error['code']
            raise AssertionError('z_mergetoaddress%r answered' % (args,))

        def paid(txid):
            return -n0.gettransaction(txid)['fee']

        fn = n0.getnewaddress('', 'pq')
        slh = n0.getnewaddress('', 'pqslh')
        ecc = n0.getnewaddress()
        zaddr = n0.z_getnewaddress('sapling')
        for _ in range(2):
            n1.sendtoaddress(fn, 1)
        for _ in range(3):
            n1.sendtoaddress(slh, 1)
        n1.sendtoaddress(ecc, 1)
        self.mine(1)
        print('  the refusals')
        assert_equal(refused('fromaddresses array is empty', [], ecc), -8)
        assert_equal(refused('duplicated address: ' + ecc, [ecc, ecc], slh), -8)
        assert_equal(refused('Cannot specify specific taddrs when using "ANY_TADDR"', ['ANY_TADDR', ecc], slh), -8)
        assert_equal(refused('Unknown address format: nonsense', ['nonsense'], slh), -8)
        assert_equal(refused('unknown address format: nonsense', [ecc], 'nonsense'), -8)
        assert_equal(refused('Could not find any funds to merge.', [n0.getnewaddress()], slh), -6)
        assert_equal(refused('Limit on maximum number of UTXOs cannot be negative', [ecc], slh, None, -1), -8)
        assert_equal(refused('Fee 0.0001 is below the', [fn], slh, Decimal('0.0001')), -8)

        print('  PQ -> PQ: the FN-DSA coins, priced on their size')
        merged_pq = n0.getnewaddress('', 'pqslh')
        r = merge([fn], merged_pq)
        assert_equal((r['mergingUTXOs'], r['remainingUTXOs'], r['mergingNotes']), (2, 0, 0))
        assert_equal(r['mergingTransparentValue'], Decimal('2'))
        txid = wait_and_assert_operationid_status(n0, r['opid'])
        print('  fee', paid(txid))
        assert_equal(paid(txid), MERGE_FEES['fn2'])
        self.mine(1)
        assert_equal(n0.z_getbalance(fn), 0)
        assert_equal(n0.z_getbalance(merged_pq), Decimal('2') - paid(txid))

        print('  PQ + ECC -> Sapling')
        r = merge([slh, ecc], zaddr)
        assert_equal((r['mergingUTXOs'], r['remainingUTXOs']), (4, 0))
        txid = wait_and_assert_operationid_status(n0, r['opid'])
        print('  fee', paid(txid))
        assert_equal(paid(txid), MERGE_FEES['slh3_ecc'])
        self.mine(3)                                  # a note is merged at the anchor depth (3)
        assert_equal(n0.z_getbalance(zaddr), Decimal('4') - paid(txid))

        print('  Sapling -> PQ; a transparent limit leaves the rest')
        merged_fn = n0.getnewaddress('', 'pq')
        r = merge(['ANY_SAPLING'], merged_fn)
        assert_equal((r['mergingUTXOs'], r['mergingNotes']), (0, 1))
        txid = wait_and_assert_operationid_status(n0, r['opid'])
        self.mine(1)
        out = n0.getrawtransaction(txid, 1)['vout'][0]['value']
        assert_equal(Decimal(r['mergingShieldedValue']) - out, Decimal('0.00001'))   # -feepolicy=peroutput
        assert_equal(n0.z_getbalance(merged_fn), out)
        small = n0.getnewaddress()
        for _ in range(3):
            n1.sendtoaddress(small, Decimal('0.5'))
        self.mine(1)
        r = merge([small], merged_fn, None, 2)
        assert_equal((r['mergingUTXOs'], r['remainingUTXOs']), (2, 1))
        assert_equal(r['remainingTransparentValue'], Decimal('0.5'))
        txid = wait_and_assert_operationid_status(n0, r['opid'])
        assert_equal(paid(txid), Decimal('0.00001'))   # ycashd's default -feepolicy=peroutput
        self.mine(1)


if __name__ == '__main__':
    GapParity().main()
