"""
yewd S6, the gap parity checks (beta3 item 14; the gaps found by the parity suite,
wt/handoff/KG-YEWD-VAULT-PARITY.md): each check states ycashd's own behaviour, passes on a plain
ycashd first, then on yewd.

Two nodes on ycash6's functional framework. Node 1 is always a plain ycashd (the miner and the
peer). Node 0 is the wallet under test: a plain ycashd when YEWD_BIN is unset (the reference
column), the pair (ycashd -disablewallet + yewd, the harness's YEWD_BIN mode) when it is set.

    YCASH6_QA=<ycash6>/qa/rpc-tests ZCASHD=<ycashd> [YEWD_BIN=<yewd>] \\
        <venv>/bin/python yewd/qa/s6_gaps.py --tmpdir=<dir> --portseed=<n> [--checks a,b]

Checks (--checks, default all), in the order of the gaps' user impact:

  lock_lifetime   a vault_lock funded by default, from a transparent or a post-quantum address
                  holds no coin lock once accepted (ycash6 src/rpc/vault.cpp FundScope, Broadcast;
                  audit L-1); a coin locked with lockunspent stays locked.
  funding_change  the funding change of a default-funded vault_lock is a fresh external key
                  (vault.cpp NewWalletKey), listed sent and received by gettransaction
                  (wallet.cpp IsChange) and kept out of the address book.
  merge           z_mergetoaddress from post-quantum, ECC and Sapling sources to post-quantum and
                  Sapling destinations (ycash6 rpcwallet.cpp z_mergetoaddress, beta2 D-6): the
                  counts, the post-quantum fee on the real size, an explicit fee below it, and the
                  refusals; the rows of ycash6 qa/wallet_address_matrix.py.
  merge_more      z_mergetoaddress's other rows (review L2): the default privacy policy merging two
                  ECC addresses into an ECC one, a memo with an ECC destination, shielded_limit
                  leaving notes as remaining, locked and unconfirmed coins skipped (not remaining),
                  and a named P2SH source (yewd refuses it, review M3; ycashd merges it).
  send_fee        z_sendmany with no fee and no post-quantum input pays the node's fee for the
                  shape (-feepolicy=peroutput: 1,000 zat), ECC to ECC, ECC to Sapling and Sapling to
                  ECC (yew_core node_fee, beta3 items 10 and 14).
  watch_only      importaddress (ECC, post-quantum, P2SH with its redeem script, rescan or not) and
                  importpubkey (ycash6 rpcdump.cpp): ycashd's refusals; the watched coins in
                  getbalance, z_gettotalbalance, listtransactions, gettransaction and
                  listreceivedbyaddress only with includeWatchonly (involvesWatchonly), in listunspent
                  as spendable false, in validateaddress (iswatchonly, pubkey), z_getbalance,
                  getreceivedbyaddress, listaddresses (imported_watchonly); every spend path refuses
                  them with ycashd's error; their owner's spend; a restart.
  help_text       every wallet method the façade serves has ycashd's help text (yewd's copy,
                  facade/src/ycashd_rpc.json, is generated by qa/gen_ycashd_rpc_table.py from a
                  ycashd at the release); getunconfirmedbalance is getwalletinfo's
                  unconfirmed_balance; the four unified-address account RPCs give ycashd's NU5
                  refusal, and a wrong argument count its usage error.
"""

